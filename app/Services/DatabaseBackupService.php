<?php

namespace App\Services;

use App\Models\ActivityLog;
use App\Models\CompanyProfile;
use Carbon\Carbon;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;

class DatabaseBackupService
{
    /**
     * Directory path where backup files are stored.
     */
    public static function getBackupDirectory(): string
    {
        $path = storage_path('app/backups');
        if (!File::exists($path)) {
            File::makeDirectory($path, 0755, true);
        }
        return $path;
    }

    /**
     * Generate a new SQL database backup file and store it in storage/app/backups.
     *
     * @param bool $isAuto Whether this backup was triggered automatically by scheduler/interval
     * @return array Metadata about the generated backup file
     */
    public static function generateBackup(bool $isAuto = false): array
    {
        $dir = self::getBackupDirectory();
        $dbName = DB::connection()->getDatabaseName();
        $prefix = $isAuto ? 'backup_auto_' : 'backup_manual_';
        $filename = $prefix . date('Y-m-d_His') . '.sql';
        $filepath = $dir . DIRECTORY_SEPARATOR . $filename;

        $handle = fopen($filepath, 'w');

        // Header comments
        fwrite($handle, "-- ======================================================\n");
        fwrite($handle, "-- PT MUDALAYA ENERGY INDONESIA - WAREHOUSE MANAGEMENT SYSTEM\n");
        fwrite($handle, "-- Database Backup Dump (.sql)\n");
        fwrite($handle, "-- Type: " . ($isAuto ? "AUTO SCHEDULED BACKUP" : "MANUAL BACKUP") . "\n");
        fwrite($handle, "-- Database: `{$dbName}`\n");
        fwrite($handle, "-- Generated: " . date('Y-m-d H:i:s') . "\n");
        fwrite($handle, "-- Generated by: " . (auth()->user()->name ?? 'System Auto Backup Engine') . "\n");
        fwrite($handle, "-- ======================================================\n\n");
        fwrite($handle, "SET FOREIGN_KEY_CHECKS=0;\n");
        fwrite($handle, "SET SQL_MODE = \"NO_AUTO_VALUE_ON_ZERO\";\n");
        fwrite($handle, "SET time_zone = \"+00:00\";\n\n");

        $tables = DB::select('SHOW TABLES');
        $tableKey = 'Tables_in_' . $dbName;
        $pdo = DB::connection()->getPdo();

        foreach ($tables as $tblObj) {
            $tableName = $tblObj->$tableKey ?? current((array) $tblObj);

            // Structure
            fwrite($handle, "-- ------------------------------------------------------\n");
            fwrite($handle, "-- Table structure for `{$tableName}`\n");
            fwrite($handle, "-- ------------------------------------------------------\n");
            fwrite($handle, "DROP TABLE IF EXISTS `{$tableName}`;\n");

            $createTableResult = DB::select("SHOW CREATE TABLE `{$tableName}`");
            if (!empty($createTableResult)) {
                $createRow = (array) $createTableResult[0];
                $createSql = $createRow['Create Table'] ?? '';
                fwrite($handle, $createSql . ";\n\n");
            }

            // Data
            fwrite($handle, "-- Dumping data for table `{$tableName}`\n");
            $rows = DB::table($tableName)->get();
            if ($rows->count() > 0) {
                $columnNames = array_keys((array) $rows->first());
                $columnsList = '`' . implode('`, `', $columnNames) . '`';

                foreach ($rows->chunk(100) as $chunk) {
                    $valuesList = [];
                    foreach ($chunk as $row) {
                        $rowValues = [];
                        foreach ((array) $row as $val) {
                            if (is_null($val)) {
                                $rowValues[] = 'NULL';
                            } elseif (is_numeric($val)) {
                                $rowValues[] = $val;
                            } else {
                                $rowValues[] = $pdo->quote($val);
                            }
                        }
                        $valuesList[] = '(' . implode(', ', $rowValues) . ')';
                    }
                    fwrite($handle, "INSERT INTO `{$tableName}` ({$columnsList}) VALUES\n" . implode(",\n", $valuesList) . ";\n");
                }
            }
            fwrite($handle, "\n");
        }

        fwrite($handle, "SET FOREIGN_KEY_CHECKS=1;\n");
        fwrite($handle, "-- Backup completed successfully on " . date('Y-m-d H:i:s') . "\n");

        fclose($handle);

        $fileSize = file_exists($filepath) ? filesize($filepath) : 0;

        // Update profile last_backup_at
        $profile = CompanyProfile::getProfile();
        $profile->update([
            'last_backup_at' => now(),
        ]);

        // Clean up retention limit
        $maxFiles = max(1, (int) ($profile->auto_backup_max_files ?? 10));
        self::cleanOldBackups($maxFiles);

        // Record Activity Log
        ActivityLog::record(
            $isAuto ? 'Auto Backup Database' : 'Manual Backup Database',
            "Membuat cadangan database baru ({$filename}) berukuran " . self::formatBytes($fileSize) . ".",
            'Pengaturan System'
        );

        return [
            'filepath' => $filepath,
            'filename' => $filename,
            'size' => $fileSize,
            'formatted_size' => self::formatBytes($fileSize),
            'created_at' => now(),
        ];
    }

    /**
     * Check whether an auto backup is currently due according to configured settings.
     */
    public static function isBackupDue(): bool
    {
        $profile = CompanyProfile::getProfile();

        if (!$profile->auto_backup_enabled) {
            return false;
        }

        if (empty($profile->last_backup_at)) {
            return true;
        }

        $nextDate = self::getNextBackupDate();
        if (!$nextDate) {
            return false;
        }

        return now()->greaterThanOrEqualTo($nextDate);
    }

    /**
     * Calculate the next scheduled backup timestamp.
     */
    public static function getNextBackupDate(): ?Carbon
    {
        $profile = CompanyProfile::getProfile();

        if (!$profile->auto_backup_enabled) {
            return null;
        }

        $val = max(1, (int) ($profile->auto_backup_frequency_value ?? 7));
        $unit = strtolower($profile->auto_backup_frequency_unit ?? 'days');

        if (empty($profile->last_backup_at)) {
            return now();
        }

        $last = Carbon::parse($profile->last_backup_at);

        return $unit === 'months' ? $last->copy()->addMonths($val) : $last->copy()->addDays($val);
    }

    /**
     * Get list of all local backup files in storage/app/backups.
     */
    public static function getBackupFiles(): array
    {
        $dir = self::getBackupDirectory();
        $files = File::glob($dir . DIRECTORY_SEPARATOR . '*.sql');

        $result = [];
        foreach ($files as $f) {
            $filename = basename($f);
            $size = filesize($f);
            $modified = filemtime($f);
            $isAuto = str_starts_with($filename, 'backup_auto_');

            $result[] = [
                'filename' => $filename,
                'path' => $f,
                'size_bytes' => $size,
                'size_formatted' => self::formatBytes($size),
                'created_at' => Carbon::createFromTimestamp($modified),
                'is_auto' => $isAuto,
            ];
        }

        // Sort descending by modified timestamp (newest first)
        usort($result, fn($a, $b) => $b['created_at']->timestamp <=> $a['created_at']->timestamp);

        return $result;
    }

    /**
     * Clean old backup files that exceed the retention limit.
     */
    public static function cleanOldBackups(int $maxFiles = 10): int
    {
        $files = self::getBackupFiles();
        if (count($files) <= $maxFiles) {
            return 0;
        }

        $deletedCount = 0;
        $filesToDelete = array_slice($files, $maxFiles);

        foreach ($filesToDelete as $item) {
            if (File::exists($item['path'])) {
                File::delete($item['path']);
                $deletedCount++;
            }
        }

        return $deletedCount;
    }

    /**
     * Restore database from a specific file path.
     */
    public static function restoreFromFile(string $filepath): bool
    {
        if (!File::exists($filepath)) {
            throw new \Exception("Berkas cadangan tidak ditemukan di server: " . basename($filepath));
        }

        $sql = File::get($filepath);
        if (empty($sql)) {
            throw new \Exception("Berkas cadangan kosong.");
        }

        DB::statement('SET FOREIGN_KEY_CHECKS=0;');
        DB::unprepared($sql);
        DB::statement('SET FOREIGN_KEY_CHECKS=1;');

        ActivityLog::record(
            'Restore Database System',
            "Memulihkan seluruh struktur & data database dari file: " . basename($filepath),
            'Pengaturan System'
        );

        return true;
    }

    /**
     * Delete a single backup file by filename.
     */
    public static function deleteBackupFile(string $filename): bool
    {
        $cleanName = basename($filename);
        $filepath = self::getBackupDirectory() . DIRECTORY_SEPARATOR . $cleanName;

        if (File::exists($filepath)) {
            File::delete($filepath);

            ActivityLog::record(
                'Hapus File Backup',
                "Menghapus berkas cadangan database ({$cleanName}) dari server.",
                'Pengaturan System'
            );

            return true;
        }

        return false;
    }

    /**
     * Helper to format byte count into readable human size.
     */
    public static function formatBytes(int $bytes, int $precision = 2): string
    {
        if ($bytes <= 0) return '0 B';
        $units = ['B', 'KB', 'MB', 'GB'];
        $i = floor(log($bytes, 1024));
        return round($bytes / pow(1024, $i), $precision) . ' ' . ($units[$i] ?? 'B');
    }
}
